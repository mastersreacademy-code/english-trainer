import {readFile,writeFile} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {dirname,resolve} from 'node:path';
const projectRoot=resolve(dirname(fileURLToPath(import.meta.url)),'..');
export function makeVersion({major,feature,sha,date=new Date()}){
if(!Number.isInteger(major)||major<1||!Number.isInteger(feature)||feature<0)throw Error('Invalid release feature');
if(sha!==null&&!/^[a-f0-9]{7,40}$/i.test(sha))throw Error('Invalid release commit');
const parts=new Intl.DateTimeFormat('en-CA',{timeZone:'Asia/Ho_Chi_Minh',year:'numeric',month:'2-digit',day:'2-digit'}).formatToParts(date);
const buildDate=['year','month','day'].map(key=>parts.find(p=>p.type===key).value).join('');
const commit=sha?sha.slice(0,7).toLowerCase():'dev';
return {version:`${major}.${feature}.${commit}.${buildDate}`,major,feature,commit,buildDate,timeZone:'Asia/Ho_Chi_Minh'};
}
export async function writeVersion(root=projectRoot){
const pkg=JSON.parse(await readFile(resolve(root,'package.json'),'utf8'));
const [major,feature]=pkg.version.split('.').map(Number);
let sha=process.env.WORKERS_CI_COMMIT_SHA||process.env.GITHUB_SHA||null;
if(!sha)try{sha=execFileSync('git',['rev-parse','HEAD'],{cwd:root,encoding:'utf8',stdio:['ignore','pipe','ignore']}).trim()}catch{}
const release=makeVersion({major,feature,sha});
await writeFile(resolve(root,'public/version.js'),`// Generated by the build. Do not edit.\nexport const buildInfo = ${JSON.stringify(release)};\n`);
console.log('Application version: '+release.version);
return release;
}
if(process.argv[1]&&import.meta.url===pathToFileURL(resolve(process.argv[1])).href)await writeVersion();
